SET LOCAL lock_timeout = '5s';

CREATE TABLE sys_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_key VARCHAR(64) NOT NULL,
    kind VARCHAR(40) NOT NULL CHECK (kind IN ('CACHE_INVALIDATE', 'STOCK_LOG_EXPORT')),
    dedupe_key VARCHAR(200) NOT NULL,
    payload JSONB NOT NULL,
    actor_user_id BIGINT REFERENCES sys_user(id),
    request_id VARCHAR(128) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','PROCESSING','RETRY_WAIT','SUCCEEDED','DEAD_LETTER','CANCELLED','EXPIRED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    lease_token UUID,
    lease_until TIMESTAMPTZ,
    cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
    error_code VARCHAR(40),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (tenant_key, kind, dedupe_key)
);
COMMENT ON TABLE sys_outbox IS '事务后台任务：业务提交、租约消费、失败重试与死信';
CREATE INDEX idx_sys_outbox_actor ON sys_outbox(actor_user_id);
CREATE INDEX idx_sys_outbox_ready ON sys_outbox(tenant_key, available_at, id) WHERE status IN ('PENDING','RETRY_WAIT');
CREATE INDEX idx_sys_outbox_lease ON sys_outbox(tenant_key, lease_until) WHERE status = 'PROCESSING';

CREATE TABLE sys_export_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_key VARCHAR(64) NOT NULL,
    owner_user_id BIGINT NOT NULL REFERENCES sys_user(id),
    outbox_id BIGINT NOT NULL UNIQUE REFERENCES sys_outbox(id),
    kind VARCHAR(40) NOT NULL CHECK (kind = 'STOCK_LOGS'),
    filters JSONB NOT NULL,
    financial_columns BOOLEAN NOT NULL,
    watermark BIGINT NOT NULL,
    row_count BIGINT NOT NULL DEFAULT 0 CHECK (row_count >= 0 AND row_count <= 1000000),
    byte_size BIGINT NOT NULL DEFAULT 0 CHECK (byte_size >= 0 AND byte_size <= 262144000),
    file_token UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    expires_at TIMESTAMPTZ
);
COMMENT ON TABLE sys_export_job IS '库存日志导出任务与私有文件记录；下载实时复核权限';
CREATE INDEX idx_sys_export_job_owner ON sys_export_job(owner_user_id, tenant_key, created_at DESC);
CREATE INDEX idx_sys_export_job_expiry ON sys_export_job(expires_at) WHERE expires_at IS NOT NULL;

CREATE TABLE sys_job_lease (
    name VARCHAR(100) PRIMARY KEY,
    lease_token UUID NOT NULL,
    lease_until TIMESTAMPTZ NOT NULL
);
COMMENT ON TABLE sys_job_lease IS '单部署后台清理任务的跨实例互斥租约';
