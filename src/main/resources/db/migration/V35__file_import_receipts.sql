SET LOCAL lock_timeout = '5s';

CREATE TABLE sys_import_receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_key VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES sys_user(id),
    operation VARCHAR(30) NOT NULL,
    scope_key VARCHAR(80) NOT NULL,
    file_hash CHAR(64) NOT NULL,
    options_hash CHAR(64) NOT NULL,
    result JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    expires_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()+interval '24 hours',
    UNIQUE (tenant_key,user_id,operation,scope_key,file_hash,options_hash)
);
COMMENT ON TABLE sys_import_receipt IS '文件实际 SHA256 与导入选项绑定的 24 小时成功回执；与全部业务行同事务提交';
CREATE INDEX idx_import_receipt_user ON sys_import_receipt(user_id);
CREATE INDEX idx_import_receipt_expiry ON sys_import_receipt(tenant_key,expires_at);
